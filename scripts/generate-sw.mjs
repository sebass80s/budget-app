/**
 * Build a versioned offline service worker for the exported Next.js app.
 * Only static app assets are cached. Private finances remain in localStorage.
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
const outDir = path.resolve("out");
const basePath = process.env.GITHUB_PAGES === "true" ? "/budget-app/" : "/";
const files = [];
async function traverse(folder, prefix = "") {
  for (const entry of await readdir(folder, { withFileTypes: true })) {
    const name = prefix ? prefix + "/" + entry.name : entry.name;
    if (entry.isDirectory()) await traverse(path.join(folder, entry.name), name);
    else if (entry.isFile() &&
      /\.(html|js|css|txt|json|webmanifest|png|svg|ico|woff2?|avif|webp)$/i.test(entry.name) &&
      name !== "sw.js") files.push(name);
  }
}
await traverse(outDir);
files.sort();
if (!files.includes("index.html") || !files.includes("manifest.webmanifest")) {
  throw new Error("Static export missing index.html or manifest.webmanifest");
}
for (const icon of ["icons/icon-192.png", "icons/icon-512.png", "icons/maskable-512.png", "icons/apple-touch-icon-180.png"]) {
  if (!files.includes(icon)) throw new Error("Missing exported PWA icon: " + icon);
}
const hash = createHash("sha256");
for (const file of files) {
  hash.update(file);
  hash.update(await readFile(path.join(outDir, file)));
}
const fingerprint = hash.digest("hex").slice(0, 16);
const urls = [...new Set([basePath, ...files.map(file => basePath + file)])];
const source = [
  "// Auto-generated by scripts/generate-sw.mjs. Do not edit by hand.",
  "const CACHE_NAME = " + JSON.stringify("budget-app-static-" + fingerprint) + ";",
  "const ROOT = " + JSON.stringify(basePath) + ";",
  "const ASSETS = " + JSON.stringify(urls) + ";",
  'self.addEventListener("install", event => {',
  '  event.waitUntil(caches.open(CACHE_NAME).then(cache => cache.addAll(ASSETS)).then(() => self.skipWaiting()));',
  '});',
  'self.addEventListener("activate", event => {',
  '  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith("budget-app-static-") && key !== CACHE_NAME).map(key => caches.delete(key)))).then(() => self.clients.claim()));',
  '});',
  'self.addEventListener("fetch", event => {',
  '  const request = event.request;',
  '  if (request.method !== "GET") return;',
  '  const url = new URL(request.url);',
  '  if (url.origin !== self.location.origin || !url.pathname.startsWith(ROOT)) return;',
  '  if (request.mode === "navigate") {',
  '    event.respondWith(fetch(request).catch(async () => (await caches.match(ROOT + "index.html")) || Response.error()));',
  '    return;',
  '  }',
  '  event.respondWith(caches.match(request).then(cached => cached || fetch(request)));',
  '});',
  ""
].join("\n");
await writeFile(path.join(outDir, "sw.js"), source);
console.log("Versioned offline SW generated: " + fingerprint + " (" + urls.length + " URLs)");
